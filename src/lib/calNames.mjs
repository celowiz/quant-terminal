/** Display name for a CAL row: curated EN/PT, else the raw name cleaned of S.A./S/A noise. */
export function calName(ticker, fallback = '', pt = false) {
  const hit = NAMES[String(ticker || '').toUpperCase()]
  if (hit) return pt ? hit.pt : hit.en
  return String(fallback || ticker || '')
    .replace(/\s*S\.?A\.?\s*$/i, '')
    .replace(/\s*S\/A\s*$/i, '')
    .trim()
}

export function dayCols(n) {
  return n <= 6 ? 1 : n <= 12 ? 2 : 3
}
